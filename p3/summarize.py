#!/usr/bin/env python3
"""Turn the CSVs in results/ into results/summary.md (tables for the paper and for P5's graphs)."""
import collections
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
ORDER = ["off", "caps", "caps+taint", "caps+taint+sandbox"]


def rd(name):
    p = os.path.join(R, name)
    return list(csv.DictReader(open(p))) if os.path.exists(p) else []


def b(x):
    return str(x).lower() == "true"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def attack_tables(rows, title):
    if not rows:
        return ""
    cfgs = [c for c in ORDER if any(r["config"] == c for r in rows)]
    act = [r for r in rows if b(r["action_level"])]
    cats = sorted({r["category"] for r in act})
    t1 = []
    for cat in cats:
        line = [cat]
        for c in cfgs:
            m = [r for r in act if r["category"] == cat and r["config"] == c]
            line.append(f"{sum(b(r['succeeded']) for r in m)}/{len(m)}")
        t1.append(line)
    tot = ["**ALL action-level**"]
    for c in cfgs:
        m = [r for r in act if r["config"] == c]
        tot.append(f"**{sum(b(r['succeeded']) for r in m)}/{len(m)}**")
    t1.append(tot)
    con = [r for r in rows if not b(r["action_level"])]
    line = ["answer_manipulation (content-level)"]
    for c in cfgs:
        m = [r for r in con if r["config"] == c]
        line.append(f"{sum(b(r['succeeded']) for r in m)}/{len(m)}")
    t1.append(line)
    layers = collections.Counter()
    for r in act:
        if r["config"] == "caps+taint" and not b(r["succeeded"]):
            layers[r["blocked_by"] or "-"] += 1
    sandbox = {c: any(b(r["sandbox_active"]) for r in rows if r["config"] == c) for c in cfgs}
    txt = [f"### {title}", "", "Attacks that SUCCEEDED (lower is better):", "", table(["category"] + cfgs, t1), ""]
    if layers:
        txt += ["Layer that blocked the attacks in `caps+taint`: " + ", ".join(f"{k} ({v})" for k, v in sorted(layers.items())), ""]
    for c in cfgs:
        if c.endswith("sandbox") and not sandbox[c]:
            txt += [f"> `{c}` ran WITHOUT a sandbox (bubblewrap not installed on this machine), so it equals `caps+taint`.", ""]
    det = [r for r in rows if r["config"] == cfgs[0]]
    txt += [f"SecurityAgent detection: {sum(b(r['detected']) for r in det)}/{len(det)} attack payloads flagged.", ""]
    return "\n".join(txt)


def main():
    parts = ["# Results summary (generated by summarize.py)", ""]
    parts.append(attack_tables(rd("attacks_scripted.csv"), "Attack suite, scripted compromised LLM, policy v2 (final)"))
    leg = rd("attacks_scripted_legacy.csv")
    if leg:
        parts.append(attack_tables(leg, "Same suite against policy v1 (before the two fixes), for docs/findings.md"))
    q = rd("attacks_qwen.csv")
    if q:
        parts.append(attack_tables(q, "Attack suite, real Qwen2.5-1.5B (subset)"))

    ben = rd("benign.csv")
    if ben:
        cfgs = [c for c in ORDER if any(r["config"] == c for r in ben)]
        rows = []
        for c in cfgs:
            m = [r for r in ben if r["config"] == c]
            rows.append([c, f"{sum(b(r['passed']) for r in m)}/{len(m)}", sum(b(r["needs_approval"]) for r in m),
                         f"{sum(b(r['passed_with_approval']) for r in m)}/{len(m)}"])
        parts += ["### Benign tasks (must keep working)", "",
                  table(["config", "pass without approval", "needs approval", "pass with approval"], rows), ""]
        m = [r for r in ben if r["config"] == cfgs[0]]
        parts += [f"SecurityAgent flagged {sum(b(r['scanner_flagged']) for r in m)}/{len(m)} benign inputs "
                  f"(scanner false positives).", ""]
        fp = [r for r in ben if r["config"] == "caps+taint" and b(r["needs_approval"])]
        if fp:
            parts += ["Needs approval under `caps+taint`: " + ", ".join(f"{r['task_id']} ({r['name']})" for r in fp), ""]

    p = os.path.join(R, "overhead.json")
    if os.path.exists(p):
        o = json.load(open(p))
        parts += ["### Policy-check overhead", "",
                  f"{o['calls']} calls (each also writes one audit-log line): mean {o['mean_ms']} ms, "
                  f"p50 {o['p50_ms']} ms, p95 {o['p95_ms']} ms, p99 {o['p99_ms']} ms.", ""]
    with open(os.path.join(R, "summary.md"), "w") as f:
        f.write("\n".join(parts))
    print("\n".join(parts))


if __name__ == "__main__":
    main()
